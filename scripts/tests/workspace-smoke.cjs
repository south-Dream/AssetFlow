// Hidden Electron renderer smoke test with deterministic resource/dialog fixtures.
const { app, BrowserWindow, ipcMain } = require("electron");
const path = require("node:path");
const fs = require("node:fs/promises");
app.disableHardwareAcceleration();
app.setPath("userData", path.resolve(`.cache/smoke-profile-${process.pid}`));
const timeout = setTimeout(() => { console.error("UI smoke timed out"); app.exit(1); }, 45000);
console.log("Starting hidden Electron UI smoke");
app.whenReady().then(async () => {
  console.log("Electron ready");
  const win = new BrowserWindow({ show: false, width: 1400, height: 850, webPreferences: { backgroundThrottling: false, preload: path.resolve("dist/node/preload/index.js"), contextIsolation: true, nodeIntegration: false } });
  const image = { id: "image", path: "C:/fixtures/picture.png", root: "C:/fixtures", name: "picture.png", format: "png", width: 1, height: 1, size: 1, thumbnail: "" };
  const audio = { ...image, id: "audio", path: "C:/fixtures/sound.wav", name: "sound.wav", format: "wav" };
  let exported;
  ipcMain.handle("systemExtensions.snapshot", () => []);
    ipcMain.handle("canvasModules.list", () => []);
  ipcMain.handle("definitions", () => []);
  ipcMain.handle("import", () => [image, audio]);
  ipcMain.handle("preview", () => ({ url: "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=", warnings: [] }));
  ipcMain.handle("exportHierarchy", (_, entries, folders, name, zip) => { exported = { entries, folders, name, zip }; return "C:/output/asset"; });
  const errors = [];
  win.webContents.on("console-message", (_, level, message) => { if (level >= 3) errors.push(message); });
  await win.loadFile(path.resolve("dist/ui/index.html"));
  console.log("Renderer loaded");
  try {
    await win.webContents.executeJavaScript(`(async () => {
      const pause = () => new Promise(r => setTimeout(r, 120));
      const check = (condition, message) => { if (!condition) throw Error(message); };
      const click = (text,root=document) => { const el = [...root.querySelectorAll('button,summary')].find(el => el.textContent.trim() === text); check(el, 'Missing menu: ' + text); if(el.tagName!=='SUMMARY'||!el.parentElement.open)el.click(); };
      await pause();
      check(document.querySelector('.main-menu'), 'Missing main menu');
      const top=document.querySelector('.dock-app > .main-menu');
      const clickTop=text=>[...top.querySelectorAll('.navigation-region > .navigation-node > button[aria-haspopup="menu"]')].find(e=>e.textContent.trim()===text).click();
      clickTop('编辑'); clickTop('文件'); await pause();
      check(top.querySelectorAll('.navigation-region > .navigation-node[data-menu-open="true"]').length===1,'Top navigation menus must be mutually exclusive');
      clickTop('编辑'); await pause();
      check(top.querySelectorAll('.navigation-region > .navigation-node[data-menu-open="true"]').length===1,'Opening a third menu did not close siblings');
      clickTop('编辑'); await pause();
      check(!document.querySelector('.add-processor'),'Inspector still contains legacy Add Module');
      const panel=document.querySelector('.generic-panel');
      check(panel.querySelector('.canvas-toolbox'),'Missing left canvas toolbox');
      const panels=[...document.querySelectorAll('.generic-panel')];
      click('编辑',panels[0].querySelector('.panel-toolbar'));click('显示编辑工具栏',panels[0].querySelector('.panel-toolbar'));await pause();
      check(!panels[0].querySelector('.canvas-toolbox')&&panels[1].querySelector('.canvas-toolbox'),'Tool visibility is shared between canvas instances');
      click('编辑',panels[0].querySelector('.panel-toolbar'));click('显示编辑工具栏',panels[0].querySelector('.panel-toolbar'));await pause();
      check(!panel.querySelector('.panel-type-trigger'),'Legacy Type control still exists');
      click('编辑',panel.querySelector('.panel-toolbar'));click('类型',panel.querySelector('.panel-toolbar'));await pause();
      check(panel.querySelector('.main-menu .navigation-node[data-menu-open="true"] .navigation-node[data-menu-open="true"] button[aria-checked="true"]'),'Type selection is not a nested unified menu: '+panel.querySelector('.panel-toolbar').innerHTML);
      click('img',panel.querySelector('.panel-toolbar'));await pause();
      const toolbox=panel.querySelector('.canvas-toolbox');
      check(toolbox.getBoundingClientRect().width<60,'Toolbox is not a narrow left rail: '+JSON.stringify({w:toolbox.getBoundingClientRect().width,flex:getComputedStyle(toolbox).flex,width:getComputedStyle(toolbox).width}));
      const tool=toolbox.querySelector('button');
      check(tool.querySelector('img')&&tool.getAttribute('aria-label')==='裁剪'&&!tool.hasAttribute('title'),'Tool icon or name/description tooltip missing');
      const connection=document.querySelector('.canvas-connections .field'),label=connection?.querySelector('span'),select=connection?.querySelector('select');
      check(label&&select&&Math.abs(label.getBoundingClientRect().top-select.getBoundingClientRect().top)<12,'Input label and selector are not arranged horizontally');
      check(!document.querySelector('.direct-tools'), 'Crop/Resize toolbar still present');
      check(!document.querySelector('.canvas-toolbar'), 'Duplicate canvas title still present');
      click('文件'); click('导入…'); await pause(); click('选择文件…'); await pause();
      check(document.querySelectorAll('.asset').length === 2, 'Generic assets did not import');
      document.querySelector('.asset-list').dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 100, clientY: 150 })); await pause();
      const input = document.querySelector('input[aria-label="文件夹名称"]'); check(input, 'Folder context menu missing');
      input.closest('form').dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })); await pause();
      check(document.querySelector('.folder-row'), 'Folder not created');
      const transfer = new DataTransfer(); transfer.setData('application/assetflow-asset', 'audio');
      document.querySelector('.folder-row').dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer })); await pause();
      document.querySelector('.folder-row').click(); await pause();
      click('文件'); click('导出…'); await pause();
      const exportDialog=document.querySelector('.export-selection-dialog');check(exportDialog,'Export selection dialog missing');
      const imageRow=[...exportDialog.querySelectorAll('.export-selection-row')].find(row=>row.textContent.trim()==='picture.png');check(imageRow,'Export file checkbox missing');imageRow.querySelector('input').click();await pause();
      document.querySelector('form.settings-dialog').dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })); await pause();
      click('编辑'); click('新建画布'); await pause();
      check(document.querySelector('.workspace-notice'), 'Panel limit should produce feedback');
    })()`);
    if (!exported || exported.name !== "AssetFlow-export" || exported.zip !== true || exported.entries.length !== 1 || exported.entries[0].id !== "audio" || exported.entries[0].folder !== "新建文件夹" || !exported.folders.includes("新建文件夹")) throw Error("Selected-folder export lost resource organization");
    if (errors.some((message) => /Uncaught|TypeError|Maximum update/.test(message))) throw Error(errors.join("\n"));
    await fs.mkdir(".cache", { recursive: true });
    await fs.writeFile(".cache/workspace-smoke.png", (await win.webContents.capturePage()).toPNG());
    console.log("Workspace UI smoke passed: menus, import, folder creation, drag collection, checkbox-selected export, panel limit.");
    app.exit(0);
  } catch (e) { console.error(e); app.exit(1); }
}).catch((e) => { console.error(e); app.exit(1); });
