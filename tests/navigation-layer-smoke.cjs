const { app, BrowserWindow, ipcMain } = require("electron");
const path = require("node:path");
app.disableHardwareAcceleration();
app.setPath("userData", path.resolve(`.cache/navigation-layer-${process.pid}`));
const timer = setTimeout(() => { console.error("Navigation layer timed out"); app.exit(1); }, 25000);
app.whenReady().then(async () => {
  for (const channel of ["definitions", "systemExtensions.snapshot"]) ipcMain.handle(channel, () => []);
  ipcMain.handle("canvasModules.list", () => [require("./shipped-records.cjs").imageRecord]);
  const win = new BrowserWindow({ show: false, width: 1500, height: 940, webPreferences: { preload: path.resolve("dist/node/preload/index.js"), contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false } });
  await win.loadFile(path.resolve("dist/ui/index.html"));
  await win.webContents.executeJavaScript(`(async () => {
    const pause = () => new Promise(resolve => setTimeout(resolve, 150));
    const check = (value, message) => { if (!value) throw Error(message); };
    await pause();
    const system = document.querySelector('[data-navigation-container="system.top"]');
    const canvases = [...document.querySelectorAll('[data-navigation-container^="canvas.top."]')];
    check(system && canvases.length, 'Missing real navigation containers');
    const edit = root => root.querySelector('[data-nav-id="system.edit"]');
    edit(system).click(); await pause();
    const popup = edit(system).parentElement.querySelector(':scope > .menu-popup');
    const editLabels=[...popup.children].map(node=>node.querySelector(':scope > button')?.textContent);
    check(editLabels.join('|')==='新建画布|设置…','System edit menu contains obsolete panel/result actions');
    const p = popup.getBoundingClientRect();
    const canvas = canvases.find(root => { const b = edit(root).getBoundingClientRect(); return Math.max(p.left, b.left) < Math.min(p.right, b.right) && Math.max(p.top, b.top) < Math.min(p.bottom, b.bottom); });
    check(canvas, 'Fixture must overlap system popup and Canvas edit');
    const b = edit(canvas).getBoundingClientRect();
    const x = (Math.max(p.left, b.left) + Math.min(p.right, b.right)) / 2;
    const y = (Math.max(p.top, b.top) + Math.min(p.bottom, b.bottom)) / 2;
    const hit = document.elementFromPoint(x, y);
    check(popup.contains(hit), 'System popup is covered by Canvas navigation: ' + hit?.outerHTML);
    edit(canvas).click(); await pause();
    check(popup.hidden, 'Opening Canvas menu must close system menu');
    const canvasPopup = edit(canvas).parentElement.querySelector(':scope > .menu-popup');
    check(!canvasPopup.hidden, 'Canvas menu must open');
    canvas.querySelector('[data-nav-id="system.type"]').click(); await pause();
    const nested = canvas.querySelector('[data-nav-id="system.type"]').parentElement.querySelector(':scope > .menu-popup');
    check(!nested.hidden && !canvasPopup.hidden, 'Recursive Canvas menu must preserve parent');
    // Put a real panel boundary through the popup to verify fixed menus escape clipping.
    const panel = canvas.closest('.dock-panel-view');
    check(panel, 'Canvas has no panel');
    const originalHeight = panel.style.maxHeight;
    panel.style.maxHeight = '32px';
    await pause();
    const n = nested.getBoundingClientRect();
    const nx = n.left + Math.min(30, n.width / 2), ny = n.top + Math.min(16, n.height / 2);
    check(ny > panel.getBoundingClientRect().bottom, 'Cross-panel hit point must lie outside Canvas panel');
    check(nested.contains(document.elementFromPoint(nx, ny)), 'Canvas submenu is clipped or covered across panel boundary');
    panel.style.maxHeight = originalHeight;
    edit(system).click(); await pause();
    check(canvasPopup.hidden && nested.hidden && !popup.hidden, 'System menu must close recursive Canvas menus');
    document.body.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })); await pause();
    check(popup.hidden, 'Outside pointer must close menu');
    edit(canvas).click(); await pause();
    document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true })); await pause();
    check(canvasPopup.hidden, 'Escape must close menu');
  })()`);
  clearTimeout(timer);
  console.log("Navigation layer smoke passed: overlap hit testing, cross-panel recursive menus, mutual exclusion, outside click and Escape.");
  app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
